#ARITHEMATIC OPERATOR
a=int(input("enter a:"))
b=int(input("enter b:"))
print("sum:",a+b)
print("difference:",a-b)
print("product:",a*b)
print("division:",a/b)
print("modulus:",a%b)
print("power:",a**b)
print("division:",a//b)#just int value!

#RELATIONAL OPERATORS
c=5
d=6
print(c==d)
print(a>b)
print(a<b)
print(a<=b)
print(a>=b)
print(a!=b)

#ASSIGNMENT OPERATOR
num=int(input("num:"))
num+=100
print(num)
num-=8
print(num)

#LOGICAL
print(not (c>d))
print((c==d) and (c<d))
print((c==d) or (c>d))


